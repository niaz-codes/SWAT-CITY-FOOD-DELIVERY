const { AndroidConfig, withAndroidManifest, withDangerousMod } = require('@expo/config-plugins');
const fs = require('fs');
const path = require('path');

/**
 * Android push-notification wiring that Expo's built-in plugins do not cover.
 *
 * Registered as a local config plugin so it is re-applied on every
 * `expo prebuild` / EAS build rather than being a one-off manual edit that gets
 * wiped the next time the native project is regenerated.
 *
 * It does three things:
 *   1. declares `POST_NOTIFICATIONS` (required from Android 13 / API 33)
 *   2. points FCM at the brand status-bar icon (`ic_notification`) and sets the
 *      brand accent colour for the notification tray dot
 *   3. copies the per-density white-silhouette icon into the res drawables
 *
 * Without (2)/(3) Android 8+ silently drops the small icon and renders FCM
 * notifications with the default grey blob or not at all.
 */

const BRAND_COLOR = '#0E9488';

/** 24dp notification icon buckets generated by scripts/build-assets.ps1. */
const DENSITIES = ['mdpi', 'hdpi', 'xhdpi', 'xxhdpi', 'xxxhdpi'];

function ensurePermission(manifest) {
  const ANDROID = AndroidConfig.Manifest.AndroidManifest;
  const name = 'android.permission.POST_NOTIFICATIONS';

  if (!Array.isArray(manifest['uses-permission'])) {
    manifest['uses-permission'] = [];
  }
  const already = manifest['uses-permission'].some((p) => p?.$?.['android:name'] === name);
  if (!already) {
    // maxSdkVersion is deliberately omitted: the runtime permission only exists
    // on API 33+, and Android ignores unknown permissions on older releases.
    manifest['uses-permission'].push({ $: { 'android:name': name } });
  }

  return manifest;
}

function ensureFcmMetaData(manifest) {
  const application = AndroidConfig.Manifest.getMainApplicationOrThrow(manifest);

  const has = (key) =>
    Array.isArray(application['meta-data']) &&
    application['meta-data'].some((m) => m?.$?.['android:name'] === key);

  if (!Array.isArray(application['meta-data'])) {
    application['meta-data'] = [];
  }

  const entries = [
    {
      'android:name': 'com.google.firebase.messaging.default_notification_icon',
      'android:resource': '@drawable/ic_notification',
    },
    {
      'android:name': 'com.google.firebase.messaging.default_notification_color',
      // Must be a colour resource, not a literal hex, or the manifest fails to inflate.
      'android:resource': '@color/notification_color',
    },
    {
      'android:name': 'com.google.firebase.messaging.default_notification_channel_id',
      'android:value': 'default',
    },
  ];

  for (const entry of entries) {
    if (!has(entry['android:name'])) {
      application['meta-data'].push({ $: entry });
    }
  }

  return manifest;
}

/** Defines @color/notification_id in colors.xml so the manifest entry resolves. */
function ensureNotificationColor(projectRoot) {
  const colorsPath = path.join(
    projectRoot,
    'android',
    'app',
    'src',
    'main',
    'res',
    'values',
    'colors.xml',
  );
  if (!fs.existsSync(colorsPath)) return;

  let xml = fs.readFileSync(colorsPath, 'utf8');
  if (xml.includes('name="notification_color"')) return;

  const entry = `  <color name="notification_color">${BRAND_COLOR}</color>\n`;
  if (xml.includes('</resources>')) {
    xml = xml.replace('</resources>', `${entry}</resources>`);
  } else {
    xml = `<?xml version="1.0" encoding="utf-8"?>\n<resources>\n${entry}</resources>\n`;
  }
  fs.writeFileSync(colorsPath, xml);
}

/** Copies the generated density buckets into the Android drawable folders. */
function copyNotificationIcons(projectRoot) {
  const resRoot = path.join(projectRoot, 'android', 'app', 'src', 'main', 'res');

  for (const density of DENSITIES) {
    const source = path.join(projectRoot, 'assets', `ic_notification-${density}.png`);
    if (!fs.existsSync(source)) {
      throw new Error(
        `[withPushNotifications] Missing ${path.relative(projectRoot, source)}. ` +
          'Run: powershell -ExecutionPolicy Bypass -File scripts\\build-assets.ps1',
      );
    }
    const targetDir = path.join(resRoot, `drawable-${density}`);
    fs.mkdirSync(targetDir, { recursive: true });
    fs.copyFileSync(source, path.join(targetDir, 'ic_notification.png'));
  }
}

module.exports = function withPushNotifications(config) {
  config = withAndroidManifest(config, (cfg) => {
    cfg.modResults = ensureFcmMetaData(ensurePermission(cfg.modResults));
    return cfg;
  });

  config = withDangerousMod(config, [
    'android',
    (cfg) => {
      ensureNotificationColor(cfg.modRequest.projectRoot);
      copyNotificationIcons(cfg.modRequest.projectRoot);
      return cfg;
    },
  ]);

  return config;
};
